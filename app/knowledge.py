def search_articles(message: str, limit: int = 3) -> list[Article]:
    words = set(re.findall(r"[\w]+", message.casefold()))
    words -= {
        "не",
        "у",
        "в",
        "на",
        "з",
        "і",
        "та",
        "до",
        "як",
        "із",
        "це",
        "що",
        "за",
        "по",
        "про",
        "а",
        "для",
        "від",
        "мене",
        "я",
        "чи",
        "the",
        "a",
        "to",
        "my",
        "i",
        "is",
    }
    scored = []
    for article in ARTICLES:
        keywords = set(re.findall(r"[\w]+", article.keywords.casefold()))
        score = len(words & keywords) * 3
        score += len(words & set(re.findall(r"[\w]+", article.title.casefold())))
        if score:
            scored.append((score, article))
    scored.sort(key=lambda item: (-item[0], item[1].id))
    return [article for _, article in scored[:limit]]
